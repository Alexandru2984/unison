const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, ro };
// Exact English texts (server details and client fallbacks) map back to a key.
const known = new Map<string, MessageKey>(
  (Object.keys(en) as MessageKey[])
    .filter((key) => !en[key].includes("{"))
    .map((key) => [en[key], key]),
);
const NETWORK_FAILURES = new Set([
  "Failed to fetch",
  "Load failed",
  "NetworkError when attempting to fetch resource.",
]);

export type Translate = (
  key: MessageKey,
  vars?: Record<string, string | number>,
) => string;

export function translator(lang: Lang): Translate {
  const dictionary = dictionaries[lang];
  return (key, vars) =>
    dictionary[key].replace(/\{(\w+)\}/g, (match, name: string) =>
      vars && name in vars ? String(vars[name]) : match,
    );
}

/** Known messages are shown in the interface language; unknown ones pass through. */
export function localizeError(lang: Lang, message: string): string {
  const t = translator(lang);
  const key = known.get(message);
  if (key) return t(key);
  if (NETWORK_FAILURES.has(message)) return t("error.unreachable");
  const rate = message.match(/^A little breathing room\. Try again in (\d+) seconds\.$/);
  if (rate) return t("error.rate", { seconds: rate[1] });
  const status = message.match(/^The request could not be completed \((\d{3})\)\. Please try again\.$/);
  if (status) return t("error.generic", { status: status[1] });
  return message;
}

export function isLang(value: unknown): value is Lang {
  return value === "en" || value === "ro";
}

export function detectLanguage(languages: readonly string[]): Lang {
  for (const language of languages) {
    const code = language.toLowerCase().split("-")[0];
    if (code === "ro" || code === "mo") return "ro";
    if (code === "en") return "en";
  }
  return "en";
}

/** Placeholder names used by a message, for dictionary consistency checks. */
export const placeholders = (lang: Lang, key: MessageKey) =>
  [...dictionaries[lang][key].matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort();
export const messageKeys = () => Object.keys(en) as MessageKey[];
